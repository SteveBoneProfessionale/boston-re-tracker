r"""Write docs/south_florida_acquisitions.md from the database.

    python -m scraper.acq_sofl_report

Generated from the LOADED rows rather than from the builder, so the document
describes what the app actually serves rather than what the pipeline believes.
Every figure is a query, not a transcription, which is why this file can be
regenerated after any rule change instead of being edited by hand -- and why a
stale number cannot survive in it.
"""

import os
import random
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

DB = os.path.join(ROOT, "data", "acquisitions.db")
OUT = os.path.join(ROOT, "docs", "south_florida_acquisitions.md")
WHERE = "source in ('miamidade_pa','pbcpao')"
LIVE = WHERE + " and coalesce(quarantined,0) = 0"

BANDS = [(5_000_000, 10_000_000, "$5M - $10M"),
         (10_000_000, 25_000_000, "$10M - $25M"),
         (25_000_000, 50_000_000, "$25M - $50M"),
         (50_000_000, 100_000_000, "$50M - $100M"),
         (100_000_000, 10 ** 13, "$100M and above")]

# The sample is RANDOM BUT FIXED. A seed means the ten rows quoted here are the
# ten rows anyone else gets, so the sample can be checked rather than taken on
# trust -- and a re-run after a rule change moves the same ten rows, which is
# what makes a diff of this file worth reading.
SEED = 20261105


def main():
    conn = sqlite3.connect("file:" + DB + "?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row

    def q(sql):
        return conn.execute(sql).fetchall()

    def one(sql):
        return conn.execute(sql).fetchone()[0]

    out = []
    w = out.append

    w("# South Florida acquisitions\n")
    w("Generated by `python -m scraper.acq_sofl_report`. Do not edit by hand.\n")
    lo = one("select min(sale_date) from transactions where " + WHERE)
    hi = one("select max(sale_date) from transactions where " + WHERE)
    w(f"Window **{lo} to {hi}**, floor **$5,000,000**, commercial only.\n")

    total = one("select count(*) from transactions where " + WHERE)
    live = one("select count(*) from transactions where " + LIVE)
    vol = one("select coalesce(sum(price),0) from transactions where " + LIVE)
    w(f"**{live} arm's-length transactions, ${vol:,}.** A further "
      f"{total - live} are recorded and excluded from every total because the "
      f"county disqualified the sale; they stay in the table carrying the "
      f"county's own reason.\n")

    # THE WINDOW ASKED FOR AND THE WINDOW COVERED ARE NOT THE SAME, and saying
    # so is the whole point of this section. Both counties' latest recorded sale
    # falls on the SAME DAY -- two independent appraisers do not stop trading in
    # concert, so that date is a publication cutoff, not a market event. Nothing
    # in this pipeline imposes it: the query runs to the end of the year.
    w("\n## What this window actually covers\n")
    monthly = q("select substr(sale_date,1,7) m, count(*) n from transactions "
                "where " + LIVE + " group by m order by m")
    per_source = q("select source, max(sale_date) latest, count(*) n "
                   "from transactions where " + WHERE + " group by source")
    cutoffs = {r["latest"] for r in per_source}
    w(f"The brief asks for 1 January 2026 to date. The records reach "
      f"**{hi}** and stop.\n")
    if len(cutoffs) == 1:
        w(f"That is a SOURCE CUTOFF, not a quiet market: both county "
          f"appraisers' last recorded sale is the same day, {hi}, and two "
          f"independent offices do not stop transacting in concert. Neither "
          f"query is bounded before the end of the year, so nothing here is "
          f"truncating them.\n")
    for r in per_source:
        w(f"- `{r['source']}` — {r['n']} rows, latest {r['latest']}")
    w("")
    w("| Month | Deals |")
    w("|---|---:|")
    for r in monthly:
        w(f"| {r['m']} | {r['n']} |")
    if len(monthly) >= 3:
        body = [r["n"] for r in monthly[:-2]]
        typical = sorted(body)[len(body) // 2]
        w(f"\nThe monthly count runs around {typical} through mid-year and then "
          f"falls away over the last two months shown. Those tail months are "
          f"**incomplete rather than slow** — a deed takes weeks to record and "
          f"longer to reach the appraiser's sales file — so they should not be "
          f"read as a market turning down, and the period after {hi} is not "
          f"covered here at all.\n")

    w("\n## By city\n")
    w("| City | Deals | Arm's length | Volume (arm's length) |")
    w("|---|---:|---:|---:|")
    for r in q("select city, count(*) n, "
               "sum(case when coalesce(quarantined,0)=0 then 1 else 0 end) a, "
               "sum(case when coalesce(quarantined,0)=0 then price else 0 end) v "
               "from transactions where " + WHERE +
               " group by city order by v desc"):
        w(f"| {r['city']} | {r['n']} | {r['a']} | ${r['v']:,} |")
    w(f"| **Total** | **{total}** | **{live}** | **${vol:,}** |")

    w("\n## By price band\n")
    w("Arm's-length transactions only.\n")
    w("| Band | Deals | Volume |")
    w("|---|---:|---:|")
    for band_lo, band_hi, label in BANDS:
        clause = f" and price >= {band_lo} and price < {band_hi}"
        n = one("select count(*) from transactions where " + LIVE + clause)
        v = one("select coalesce(sum(price),0) from transactions where "
                + LIVE + clause)
        w(f"| {label} | {n} | ${v:,} |")

    w("\n## By asset class\n")
    w("| Class | Deals | Volume | Median $/SF |")
    w("|---|---:|---:|---:|")
    for r in q("select coalesce(asset_class,'(unclassified)') c, count(*) n, "
               "sum(price) v from transactions where " + LIVE +
               " group by c order by v desc"):
        psf = [x[0] for x in q(
            "select price_per_sf from transactions where " + LIVE +
            " and coalesce(asset_class,'(unclassified)') = '" + r["c"] + "'"
            " and price_per_sf is not null order by price_per_sf")]
        med = f"${psf[len(psf) // 2]:,.0f}" if psf else "-"
        w(f"| {r['c']} | {r['n']} | ${r['v']:,} | {med} |")
    w("\nThe medians mix no bases: a Land row divides by LAND area and every "
      "other class divides by building area, so the Land median is dollars per "
      "land foot and is not comparable with the rows above it.\n")

    w("\n## Partial stakes\n")
    stakes = one("select count(*) from transactions where " + WHERE +
                 " and pct_acquired is not null")
    w(f"**{stakes}.** Neither county publishes a conveyed percentage, and a "
      f"deed stating a price does not say whether that price bought the whole "
      f"asset or a share of it. The brief's second source for stakes is trade "
      f"press; this is the county-record spine only, so the column is empty "
      f"rather than inferred. A percentage derived from a price would be "
      f"arithmetic presented as a fact.\n")

    w("\n## Change in basis\n")
    with_pct = one("select count(*) from transactions where " + WHERE +
                   " and basis_change_pct is not null")
    with_prior = one("select count(*) from transactions where " + WHERE +
                     " and prior_sale_price is not null")
    w(f"{with_prior} of {total} rows carry a prior recorded sale and "
      f"{with_pct} carry a percentage. Where a prior sale appears WITHOUT a "
      f"percentage the figure is withheld, not missing: the earlier sale was "
      f"disqualified by the county, recorded no price or only a nominal sum, "
      f"bought land that the building now standing postdates, or covered a "
      f"different set of parcels. Every such row names its own reason.\n")

    w("\n## Links to the development pipeline\n")
    linked = q("select address, city, price, asset_class, link_basis "
               "from transactions where " + WHERE +
               " and linked_project_id is not null order by price desc")
    w(f"{len(linked)} transactions share a parcel with a Projects row - the "
      f"land trade and the building now going up on it.\n")
    w("| Transaction | City | Price | Class | Project |")
    w("|---|---|---:|---|---|")
    for r in linked:
        basis = str(r["link_basis"] or "")
        proj = (basis.split("record ")[-1].strip("'\"")
                if "record " in basis else basis)
        w(f"| {r['address']} | {r['city']} | ${r['price']:,} | "
          f"{r['asset_class']} | {proj} |")

    w("\n## Sponsor resolution\n")
    res_b = one("select count(*) from transactions where " + LIVE +
                " and coalesce(buyer_canonical,'') <> ''")
    res_s = one("select count(*) from transactions where " + LIVE +
                " and coalesce(seller_canonical,'') <> ''")
    w(f"| Side | Resolved to a firm | Entity of record | Rows |")
    w("|---|---:|---:|---:|")
    w(f"| Buyer | {res_b} | {live - res_b} | {live} |")
    w(f"| Seller | {res_s} | {live - res_s} | {live} |")
    w("\nA resolution needs either a trade-press article about THIS deal, or "
      "two independent signals that agree — a registered manager, a c/o on "
      "the deed, a chain of managers followed up to an operating company. One "
      "clue alone never resolves, and an entity that does not resolve keeps "
      "its own name and is marked as the entity of record.\n")

    w("\n### Top buyers by deal count, grouped by firm\n")
    w("A firm that bought through several single-purpose vehicles counts "
      "once, with all its deals.\n")
    w("| Firm | Deals | Volume |")
    w("|---|---:|---:|")
    for r in q("select buyer_canonical f, count(*) n, sum(price) v "
               "from transactions where " + LIVE +
               " and coalesce(buyer_canonical,'') <> '' "
               "group by f order by n desc, v desc limit 10"):
        w(f"| {r['f']} | {r['n']} | ${r['v']:,} |")

    w("\n### Ten resolutions, with their sources\n")
    w("Seeded, so this is a checkable sample rather than a chosen one.\n")
    res = [dict(r) for r in q(
        "select address, city, price, buyer, buyer_canonical, "
        "buyer_resolution_basis, buyer_resolution_url, seller, "
        "seller_canonical, seller_resolution_basis, seller_resolution_url "
        "from transactions where " + LIVE +
        " and (coalesce(buyer_canonical,'') <> '' or "
        "coalesce(seller_canonical,'') <> '')")]
    flat = []
    for r in res:
        for side in ("buyer", "seller"):
            if (r.get(f"{side}_canonical") or "").strip():
                flat.append((side, r))
    rng2 = random.Random(SEED)
    for n, (side, r) in enumerate(rng2.sample(flat, min(10, len(flat))), 1):
        w(f"**{n}. {r[side + '_canonical']}** — {side} of {r['address']}, "
          f"{r['city']}, ${r['price']:,}  ")
        w(f"entity of record: `{r[side] or '(none published)'}`  ")
        w(f"basis: {r[side + '_resolution_basis']}  ")
        w(f"source: {r[side + '_resolution_url']}\n")

    w("\n## Random sample of ten\n")
    w(f"Seeded ({SEED}), so the sample is reproducible and checkable rather "
      f"than chosen.\n")
    rows = [dict(r) for r in q("select * from transactions where " + LIVE)]
    rng = random.Random(SEED)
    for n, r in enumerate(rng.sample(rows, min(10, len(rows))), 1):
        basis = ("land SF" if not r["building_sf"] and r["land_sf"]
                 else "building SF")
        psf = f"${r['price_per_sf']:,.0f} per {basis}" if r["price_per_sf"] else "-"
        ppu = f"${r['price_per_unit']:,.0f} per unit" if r["price_per_unit"] else "-"
        chg = (f"{r['basis_change_pct']:+.1f}%"
               if r["basis_change_pct"] is not None else "not comparable")
        prior = (f"{r['prior_sale_date']} ${r['prior_sale_price']:,}"
                 if r["prior_sale_price"] else "none recorded")
        w(f"**{n}. {r['address']} - {r['city']}**  ")
        w(f"{r['sale_date']} · ${r['price']:,} · {r['asset_class']} · "
          f"`{r['property_type']}`  ")
        w(f"seller {r['seller'] or '(not published)'} -> "
          f"buyer {r['buyer'] or '(not published)'}  ")
        w(f"building {r['building_sf'] or 0:,} sf · land {r['land_sf'] or 0:,} sf "
          f"· units {r['unit_count'] or '-'} · {psf} · {ppu}  ")
        w(f"deed {r['deed_book']}/{r['deed_page']} · prior sale {prior} · "
          f"change {chg}\n")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    conn.close()
    print(f"wrote {OUT}  ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
